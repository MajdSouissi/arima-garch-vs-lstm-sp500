"""
=============================================================================
05_lstm_data_preparation.py
LSTM Data Preprocessing and Sequence Generation
=============================================================================
Creates strictly out-of-sample features, sequences, and scales data using 
only the training set for fit. Generates sequences across the continuous 
timeline first, then assigns to splits based on target dates to perfectly 
align with the GARCH evaluation.
=============================================================================
"""

import pandas as pd
import numpy as np
import os
from pathlib import Path
from sklearn.preprocessing import StandardScaler
import pickle

# â”€â”€ Paths â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
BASE_DIR = str(Path(__file__).resolve().parent.parent)
INPUT_CSV = os.path.join(BASE_DIR, "SP500_master_2000_2026.csv")
OUTPUT_DIR = os.path.join(BASE_DIR, "lstm_data")
os.makedirs(OUTPUT_DIR, exist_ok=True)

# â”€â”€ 1. Data Loading & Feature Engineering â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
print("Loading data and engineering features...")
df = pd.read_csv(INPUT_CSV, parse_dates=['Date'])
df = df.dropna(subset=['Log_Return']).reset_index(drop=True)

# Engineer enhanced features
df['Return_Sq'] = df['Log_Return'] ** 2
df['Rolling_Vol_21'] = df['Log_Return'].rolling(window=21).std()
df['Rolling_MAE_21'] = df['Log_Return'].abs().rolling(window=21).mean()

# Drop NaNs generated by rolling windows
df = df.dropna().reset_index(drop=True)

# Targets for t+1
df['Target_Return'] = df['Log_Return'].shift(-1)
df['Target_Vol']    = df['Return_Sq'].shift(-1)  # Volatility proxy: r^2_{t+1}
df['Target_Date']   = df['Date'].shift(-1)
df = df.dropna().reset_index(drop=True)

# â”€â”€ 2. Data Splitting Dates â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
train_end_dt = pd.to_datetime('2018-12-31')
val_end_dt   = pd.to_datetime('2022-12-31')

# â”€â”€ 3. Scaling â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
print("Scaling features...")
feature_cols_base = ['Log_Return']
feature_cols_enhanced = ['Log_Return', 'Return_Sq', 'Rolling_Vol_21', 'Rolling_MAE_21']

scaler_base = StandardScaler()
scaler_enhanced = StandardScaler()

# Fit on train ONLY (where the *current* date is <= train_end_dt)
train_mask = df['Date'] <= train_end_dt
scaler_base.fit(df.loc[train_mask, feature_cols_base])
scaler_enhanced.fit(df.loc[train_mask, feature_cols_enhanced])

with open(os.path.join(OUTPUT_DIR, 'scaler_base.pkl'), 'wb') as f:
    pickle.dump(scaler_base, f)
with open(os.path.join(OUTPUT_DIR, 'scaler_enhanced.pkl'), 'wb') as f:
    pickle.dump(scaler_enhanced, f)

# Transform entire dataset
base_scaled = scaler_base.transform(df[feature_cols_base])
enh_scaled  = scaler_enhanced.transform(df[feature_cols_enhanced])

target_ret  = df['Target_Return'].values
target_vol  = df['Target_Vol'].values
target_dates = df['Target_Date'].values

# â”€â”€ 4. Sequence Generation (Lookback = 60) â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
print("Generating time-series sequences (lookback=60)...")
LOOKBACK = 60

seq_X_base, seq_X_enh, seq_y_ret, seq_y_vol, seq_dates = [], [], [], [], []

for i in range(len(df) - LOOKBACK + 1): # +1 to include the last possible window
    # The lookback window ends at i + LOOKBACK - 1
    # The target is at i + LOOKBACK - 1
    # Wait, df['Target_Return'] at row `idx` is the target for date `idx + 1`.
    # Let window be row i to row i+LOOKBACK-1.
    idx = i + LOOKBACK - 1
    seq_X_base.append(base_scaled[i : idx + 1])
    seq_X_enh.append(enh_scaled[i : idx + 1])
    seq_y_ret.append(target_ret[idx])
    seq_y_vol.append(target_vol[idx])
    seq_dates.append(target_dates[idx])

seq_X_base = np.array(seq_X_base)
seq_X_enh  = np.array(seq_X_enh)
seq_y_ret  = np.array(seq_y_ret)
seq_y_vol  = np.array(seq_y_vol)
seq_dates  = np.array(seq_dates)

# â”€â”€ 5. Assign to Splits by Target Date â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
print("Assigning sequences to splits based on exact target dates...")
train_idx = seq_dates <= train_end_dt
val_idx   = (seq_dates > train_end_dt) & (seq_dates <= val_end_dt)
test_idx  = seq_dates > val_end_dt

print(f"Train Sequences: {np.sum(train_idx)}")
print(f"Val Sequences:   {np.sum(val_idx)}")
print(f"Test Sequences:  {np.sum(test_idx)}")

def get_split(mask):
    return seq_X_base[mask], seq_X_enh[mask], seq_y_ret[mask], seq_y_vol[mask], seq_dates[mask]

X_train_base, X_train_enh, y_train_ret, y_train_vol, _ = get_split(train_idx)
X_val_base,   X_val_enh,   y_val_ret,   y_val_vol,   _ = get_split(val_idx)
X_test_base,  X_test_enh,  y_test_ret,  y_test_vol,  test_dates = get_split(test_idx)

# â”€â”€ 6. Save Arrays â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
print("Saving arrays...")
np.save(os.path.join(OUTPUT_DIR, 'seq_X_train_base.npy'), X_train_base)
np.save(os.path.join(OUTPUT_DIR, 'seq_y_train_ret.npy'), y_train_ret)

np.save(os.path.join(OUTPUT_DIR, 'seq_X_val_base.npy'), X_val_base)
np.save(os.path.join(OUTPUT_DIR, 'seq_y_val_ret.npy'), y_val_ret)

np.save(os.path.join(OUTPUT_DIR, 'seq_X_test_base.npy'), X_test_base)
np.save(os.path.join(OUTPUT_DIR, 'seq_y_test_ret.npy'), y_test_ret)

np.save(os.path.join(OUTPUT_DIR, 'seq_X_train_enh.npy'), X_train_enh)
np.save(os.path.join(OUTPUT_DIR, 'seq_y_train_vol.npy'), y_train_vol)

np.save(os.path.join(OUTPUT_DIR, 'seq_X_val_enh.npy'), X_val_enh)
np.save(os.path.join(OUTPUT_DIR, 'seq_y_val_vol.npy'), y_val_vol)

np.save(os.path.join(OUTPUT_DIR, 'seq_X_test_enh.npy'), X_test_enh)
np.save(os.path.join(OUTPUT_DIR, 'seq_y_test_vol.npy'), y_test_vol)

np.save(os.path.join(OUTPUT_DIR, 'test_dates.npy'), test_dates)

print("LSTM Data Preparation Complete!")
